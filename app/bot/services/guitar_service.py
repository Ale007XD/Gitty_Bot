    def get_chord_diagram(self, chord_name: str) -> Optional[str]:
        """Получить текстовую диаграмму аккорда"""
        chord_name_upper = chord_name.upper()
        if chord_name_upper in self.basic_chords:
            return self.basic_chords[chord_name_upper]["diagram"]
        return None

    def get_guitar_parts_info(self) -> str:
        """Получить информацию о частях гитары"""
        info = "🎸 **ЧАСТИ ГИТАРЫ** 🎸\n\n"

        for part, description in self.guitar_parts.items():
            info += f"🔸 **{part.upper()}**: {description}\n"

        info += "\n💡 Запомни эти части - они важны для обучения!"
        return info

    def get_strings_info(self) -> str:
        """Получить информацию о струнах"""
        info = "🎸 **СТРУНЫ ГИТАРЫ** 🎸\n\n"

        info += "Струны считаются снизу вверх (от самой тонкой к самой толстой):\n\n"

        for i, (string_name, mnemonic_word) in enumerate(zip(self.string_names, self.string_mnemonic.split())):
            string_num = i + 1
            thickness = ""
            if string_num == 1:
                thickness = " (самая тонкая)"
            elif string_num == 6:
                thickness = " (самая толстая)"

            info += f"🎵 **{string_num}-я струна**: {string_name} - \"{mnemonic_word}\"{thickness}\n"

        info += f"\n🧠 **Мнемоника для запоминания**: \"{self.string_mnemonic}\"\n"
        info += "\n💡 Запомни эту фразу, и ты всегда будешь знать названия струн!"

        return info

    def get_chord_info(self, chord_name: str) -> Optional[Dict]:
        """Получить информацию об аккорде"""
        chord_name_upper = chord_name.upper()
        return self.basic_chords.get(chord_name_upper)

    def get_available_chords(self) -> List[str]:
        """Получить список доступных аккордов"""
        return list(self.basic_chords.keys())

